#!/usr/bin/env python3
"""Regenerate distinct, region-separated, round-trip route files for the two
TRIDENT scenarios, using randomTrips.py + duarouter for guaranteed-valid routes.

URBAN  : dense, low-speed, central downtown box; many intermediate waypoints so
         vehicles circulate and return toward their origin (round-trip feel).
HIGHWAY: sparse, high-speed; long cross-map journeys on the fast arterials.

Each random vehicle is given a passenger-class gui type (sedan/suv/sport/taxi)
so the GUI renders varied 3D-style shapes; a handful of explicit special
vehicles (bus, emergency, truck) are appended on the longest discovered routes
for visual richness. Type assignment is deterministic (by index) for repeatable
runs. Output: urban_enhanced.rou.xml, highway_enhanced.rou.xml.
"""
import os, sys, subprocess, xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.join(os.environ["SUMO_HOME"], "tools")
RANDOMTRIPS = os.path.join(TOOLS, "randomTrips.py")
NET = "aljubail_saudi.net.xml"

# passenger-class types (all allowed on the routed edges) for the random fleet
URBAN_TYPES = ["passenger_sedan", "passenger_suv", "passenger_sport",
               "passenger_taxi", "passenger_sedan", "passenger_suv"]
HIGHWAY_TYPES = ["passenger_sedan", "passenger_suv", "passenger_sport",
                 "passenger_sedan", "passenger_suv", "passenger_sedan"]

SCEN = {
    "urban": dict(weights="urban", seed="23", period="1.2", begin="0", end="600",
                  intermediate="4", fringe="1", mindist="600",
                  types=URBAN_TYPES, depspeed="max", deplane="best"),
    "highway": dict(weights="highway", seed="56", period="1.8", begin="0", end="600",
                    intermediate="3", fringe="4", mindist="3000",
                    types=HIGHWAY_TYPES, depspeed="max", deplane="free"),
}


def run(cmd):
    print("  $", " ".join(cmd))
    subprocess.run(cmd, check=True, cwd=HERE)


def gen(name, cfg):
    print(f"== {name} ==")
    trips = f"{name}.gen.trips.xml"
    raw = f"{name}.gen.rou.xml"
    # 1) random trips biased into the region, with intermediate waypoints
    run([sys.executable, RANDOMTRIPS, "-n", NET, "-o", trips,
         "--weights-prefix", cfg["weights"], "--seed", cfg["seed"],
         "-b", cfg["begin"], "-e", cfg["end"], "-p", cfg["period"],
         "--intermediate", cfg["intermediate"], "--fringe-factor", cfg["fringe"],
         "--min-distance", cfg["mindist"], "--vehicle-class", "passenger",
         "--validate", "--remove-loops"])
    # 2) duarouter -> guaranteed-valid routes (repair drops disconnected ones)
    run(["duarouter", "-n", NET, "--route-files", trips, "-o", raw,
         "--additional-files", "vTypes.add.xml", "--repair",
         "--remove-loops", "--ignore-errors",
         "--no-step-log", "true"])
    return raw


def rewrite(name, raw, cfg):
    """Assign varied gui types + add special vehicles; emit the final rou.xml."""
    tree = ET.parse(os.path.join(HERE, raw))
    root = tree.getroot()
    vehicles = [v for v in root if v.tag == "vehicle"]
    # rank by route length to pick "longest" routes for special vehicles
    def route_len(v):
        r = v.find("route")
        return len(r.get("edges").split()) if r is not None else 0
    vehicles_sorted = sorted(vehicles, key=route_len, reverse=True)

    types = cfg["types"]
    for i, v in enumerate(vehicles):
        v.set("type", types[i % len(types)])
        v.set("departLane", cfg["deplane"])
        v.set("departSpeed", cfg["depspeed"])

    out = os.path.join(HERE, f"{name}_enhanced.rou.xml")
    header = (f'<?xml version="1.0" encoding="UTF-8"?>\n'
              f'<!-- VeReMiVNDN/TRIDENT - {name} routes (region-separated, '
              f'round-trip mobility). Auto-generated by generate_routes.py from '
              f'{NET} via randomTrips.py + duarouter; do not hand-edit. -->\n'
              f'<routes xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
              f'xsi:noNamespaceSchemaLocation='
              f'"http://sumo.dlr.de/xsd/routes_file.xsd">\n')
    # (depart, xml) tuples; SUMO requires the route file sorted by departure.
    entries = []
    for v in vehicles:
        r = v.find("route")
        edges = r.get("edges")
        entries.append((float(v.get("depart")),
            f'    <vehicle id="{v.get("id")}" type="{v.get("type")}" '
            f'depart="{v.get("depart")}" departLane="{v.get("departLane")}" '
            f'departSpeed="{v.get("departSpeed")}">\n'
            f'        <route edges="{edges}"/>\n    </vehicle>'))

    # ---- special vehicles for visual richness on the longest valid routes ----
    longest = [v.find("route").get("edges") for v in vehicles_sorted[:8]]
    specials = []
    if name == "urban":
        spec_defs = [("bus_line_1", "bus_city", "10", "0.0,0.7,0.3"),
                     ("ambulance_1", "emergency", "65", "1.0,0.0,0.0"),
                     ("delivery_1", "truck_delivery", "20", "0.8,0.5,0.2"),
                     ("taxi_special", "passenger_taxi", "5", "1.0,1.0,0.0")]
    else:
        spec_defs = [("intercity_bus_1", "bus_coach", "10", "0.0,0.4,0.8"),
                     ("highway_patrol_1", "emergency", "70", "1.0,0.0,0.0"),
                     ("container_1", "truck_container", "25", "0.4,0.4,0.4"),
                     ("sport_1", "passenger_sport", "5", "1.0,0.0,0.0")]
    for idx, (vid, vtype, dep, color) in enumerate(spec_defs):
        edges = longest[idx % len(longest)]
        extra = ' <param key="has.bluelight.device" value="true"/>' \
            if vtype == "emergency" else ""
        entries.append((float(dep),
            f'    <vehicle id="{vid}" type="{vtype}" depart="{dep}" '
            f'color="{color}" departLane="best" departSpeed="max">\n'
            f'        <route edges="{edges}"/>{extra}\n    </vehicle>'))
        specials.append(vid)

    # stable-sort by departure time (SUMO requirement) then write
    entries.sort(key=lambda e: e[0])
    with open(out, "w") as f:
        f.write(header)
        f.write("\n".join(x[1] for x in entries) + "\n")
        f.write("</routes>\n")
    print(f"  wrote {os.path.basename(out)}: {len(vehicles)} random + "
          f"{len(specials)} special vehicles (depart-sorted)")
    return len(vehicles)


for name, cfg in SCEN.items():
    raw = gen(name, cfg)
    rewrite(name, raw, cfg)
