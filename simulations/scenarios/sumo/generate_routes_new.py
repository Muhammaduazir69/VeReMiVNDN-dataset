#!/usr/bin/env python3
"""Round-trip route generation for the two purpose-built TRIDENT maps.

URBAN_GRID      : dense, low-speed, many intermediate waypoints -> cars circulate
                  the grid and return (round-trip feel).
HIGHWAY_CORRIDOR: sparse, high fringe-factor + long min-distance -> long runs the
                  full length of the corridor.
randomTrips.py + duarouter guarantee connected, valid routes. Output is
depart-sorted with varied passenger gui-types (+ a few special vehicles).
"""
import os, sys, subprocess, xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.join(os.environ["SUMO_HOME"], "tools")
RANDOMTRIPS = os.path.join(TOOLS, "randomTrips.py")

TYPES = ["passenger_sedan", "passenger_suv", "passenger_sport",
         "passenger_taxi", "passenger_sedan", "passenger_suv"]

SCEN = {
    "urban_grid": dict(net="urban_grid.net.xml", seed="23", period="0.7",
                       begin="0", end="600", intermediate="3", fringe="2",
                       mindist="450", deplane="best", depspeed="max",
                       specials=[("bus_line_1", "bus_city", "8", "0,180,90"),
                                 ("ambulance_1", "emergency", "62", "230,0,0"),
                                 ("delivery_1", "truck_delivery", "18", "205,130,50"),
                                 ("taxi_1", "passenger_taxi", "4", "255,210,0")]),
    "highway_corridor": dict(net="highway_corridor.net.xml", seed="56",
                             period="0.55", begin="0", end="600", intermediate="1",
                             fringe="8", mindist="1500", deplane="free",
                             depspeed="max",
                             specials=[("intercity_bus_1", "bus_coach", "8", "0,100,200"),
                                       ("patrol_1", "emergency", "66", "230,0,0"),
                                       ("container_1", "truck_container", "20", "100,100,100"),
                                       ("sport_1", "passenger_sport", "4", "230,0,0")]),
}


def run(cmd):
    print("  $", " ".join(str(c) for c in cmd))
    subprocess.run(cmd, check=True, cwd=HERE)


def gen(name, cfg):
    print(f"== {name} ==")
    trips, raw = f"{name}.gen.trips.xml", f"{name}.gen.rou.xml"
    run([sys.executable, RANDOMTRIPS, "-n", cfg["net"], "-o", trips,
         "--seed", cfg["seed"], "-b", cfg["begin"], "-e", cfg["end"],
         "-p", cfg["period"], "--intermediate", cfg["intermediate"],
         "--fringe-factor", cfg["fringe"], "--min-distance", cfg["mindist"],
         "--vehicle-class", "passenger", "--validate", "--remove-loops"])
    run(["duarouter", "-n", cfg["net"], "--route-files", trips, "-o", raw,
         "--additional-files", "vTypes.add.xml", "--repair", "--remove-loops",
         "--ignore-errors", "--no-step-log", "true"])
    return raw


def rewrite(name, raw, cfg):
    root = ET.parse(os.path.join(HERE, raw)).getroot()
    vehicles = [v for v in root if v.tag == "vehicle"]
    rlen = lambda v: len(v.find("route").get("edges").split()) if v.find("route") is not None else 0
    longest = [v.find("route").get("edges")
               for v in sorted(vehicles, key=rlen, reverse=True)[:8]]

    entries = []
    for i, v in enumerate(vehicles):
        edges = v.find("route").get("edges")
        entries.append((float(v.get("depart")),
            f'    <vehicle id="{v.get("id")}" type="{TYPES[i % len(TYPES)]}" '
            f'depart="{v.get("depart")}" departLane="{cfg["deplane"]}" '
            f'departSpeed="{cfg["depspeed"]}">\n'
            f'        <route edges="{edges}"/>\n    </vehicle>'))
    for idx, (vid, vtype, dep, color) in enumerate(cfg["specials"]):
        edges = longest[idx % len(longest)]
        extra = ' <param key="has.bluelight.device" value="true"/>' if vtype == "emergency" else ""
        entries.append((float(dep),
            f'    <vehicle id="{vid}" type="{vtype}" depart="{dep}" color="{color}" '
            f'departLane="best" departSpeed="max">\n'
            f'        <route edges="{edges}"/>{extra}\n    </vehicle>'))
    entries.sort(key=lambda e: e[0])

    out = os.path.join(HERE, f"{name}.rou.xml")
    with open(out, "w") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n')
        f.write(f'<!-- TRIDENT {name} round-trip routes. Auto-generated by '
                f'generate_routes_new.py; do not hand-edit. -->\n')
        f.write('<routes xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
                'xsi:noNamespaceSchemaLocation='
                '"http://sumo.dlr.de/xsd/routes_file.xsd">\n')
        f.write("\n".join(x[1] for x in entries) + "\n</routes>\n")
    print(f"  wrote {os.path.basename(out)}: {len(vehicles)} random + "
          f"{len(cfg['specials'])} special (depart-sorted)")


for name, cfg in SCEN.items():
    rewrite(name, gen(name, cfg), cfg)
